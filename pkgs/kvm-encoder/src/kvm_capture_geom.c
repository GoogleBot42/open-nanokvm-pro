/*
 * kvm_capture_geom.c -- geometry parameterization for the blob-free capture
 * backend (issue #17). See kvm_capture_geom.h for the contract.
 *
 * WHERE GEOMETRY LIVES ON THE WIRE (docs/blob-replacement.md is the authority;
 * the offsets below were re-derived mechanically from the captured payloads by
 * scanning them for u32 words equal to 1920 / 1080, and cross-checked against
 * the vendor-MPI struct fields kvm_pipeline.c fills for the same call):
 *
 *   os_mem nr1 descriptor  word0 = width, word1 = height   (the ONE genuine
 *       pointer arg on the capture path; Stage 3 differential capture proved
 *       resolution is parameterised by exactly these two u32s)
 *   pool nr22 floorplan    BlkSize@0x30 = stride * height * 2  (YUYV)
 *   proton nr17/nr21 dev attr (376 B)   width@0x58  height@0x5c  stride@0xdc
 *   proton nr21 dev attr #2  (376 B)    width@0x58  height@0x5c  (0xdc stays 0)
 *   proton nr35 CreatePipe    (76 B)    width@0x1c  height@0x20  (no stride)
 *   proton nr42 SetPipeAttr   (76 B)    width@0x1c  height@0x20  stride@0x24
 *   proton nr48 SetChnAttr    (48 B)    width@0x08  height@0x0c  stride@0x10
 *
 * NOT geometry-bearing, therefore left verbatim (verified by the same scan --
 * none of them contains a 1920/1080/3840 word anywhere at any alignment):
 *   mipi nr2 SetAttr    {idx, lanes=4, rate=0x258, lanemap} -- the DPHY link
 *       rate is a fixed 600 Mbps/lane on this board (the vendor-MPI backend
 *       hardcodes KVM_MIPI_RATE=600 for every resolution too, kvm_pipeline.c).
 *   proton nr56 black_level / nr74 scene_attr / nr54 partition_info /
 *       nr89 npu_throttle -- ISP-bypass datapath config, no geometry words.
 *   proton nr101 GetYuvFrame descriptor, nr30/nr22 dev binds, nr55 EnableChn.
 *
 * ASSUMPTIONS (the RE record is SILENT here -- the only full-struct capture
 * that exists is 1080p, so no vendor bytes for another resolution were ever
 * observed; each of these is a no-op at 1920x1080):
 *   A1. The three "second width" fields (dev attr @0xdc, pipe nr42 @0x24, chn
 *       nr48 @0x10) are line strides in PIXELS. Evidence: each is the only
 *       width-valued word in its payload besides the image region; for nr42
 *       and nr48 it sits immediately after the {width,height} pair, exactly
 *       where AX_VIN_PIPE_ATTR_T.nWidthStride / AX_VIN_CHN_ATTR_T.nWidthStride
 *       sit in the SDK structs (both of which kvm_pipeline.c sets to the
 *       width on the vendor-MPI path); AX_VIN_DEV_ATTR_T likewise has an
 *       nWidthStride[] array after its tDevImgRgn[], though the marshaled
 *       kernel struct reorders enough that @0xdc cannot be matched to it by
 *       offset arithmetic. Handing the encoder u32PicStride = width is
 *       separately device-confirmed (Stage 6: the H.264 is not sheared).
 *   A2. Stride is padded up to KVM_GEOM_STRIDE_ALIGN pixels (see the header).
 *   A3. CreatePipe (nr35) genuinely has no stride field: the captured bytes at
 *       @0x24 are ZERO for nr35 while nr42's are 0x780, i.e. the vendor sends
 *       a shorter effective struct for create. We reproduce that exactly.
 *   A4. dev attr #2 keeps @0xdc = 0 and the {01,02,03} lane bytes cleared,
 *       exactly as captured -- only its width/height words are parameterised.
 */
