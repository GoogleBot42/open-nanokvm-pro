/* Explicit little-endian store: the payloads are LE on the wire (aarch64 LE
 * target) and this keeps the host-side self-test endian-independent. */
static void put_u32le(unsigned char *p, unsigned off, uint32_t v)
{
    p[off + 0] = (unsigned char)(v & 0xffu);
    p[off + 1] = (unsigned char)((v >> 8) & 0xffu);
    p[off + 2] = (unsigned char)((v >> 16) & 0xffu);
    p[off + 3] = (unsigned char)((v >> 24) & 0xffu);
}

static int align_up_i(int v, int a) { return (v + a - 1) / a * a; }

int kvm_geom_check(int w, int h, const char **why)
{
    const char *reason = NULL;

    if (w <= 0 || h <= 0)
        reason = "no source geometry (HDMI unlocked?)";
    else if (w % KVM_GEOM_W_ALIGN || h % KVM_GEOM_H_ALIGN)
        reason = "odd width/height: a YUYV macropixel is 2 px, so the VIN "
                 "cannot emit an odd line";
    else if (w < KVM_GEOM_MIN_W || h < KVM_GEOM_MIN_H)
        reason = "below the minimum supported frame (64x64)";
    /* Upper bound: the DPHY link is fixed at 4 lanes x 600 Mbps = 2.4 Gbps
     * (kvm_pipeline.h KVM_MIPI_RATE; the vendor uses the same rate at every
     * resolution and we have no decoded way to program another). YUV422-8 is
     * 16 bpp, so ~2.5 Mpx/frame at 60 Hz saturates the link; 1920x1200 is the
     * largest standard HDMI mode inside that budget, and 1920 is also the
     * widest geometry the captured pipe has ever been proven at. Anything
     * bigger would not lock even if the payloads accepted it. */
    else if (w > KVM_GEOM_MAX_W || h > KVM_GEOM_MAX_H)
        reason = "beyond the open-capture envelope (max 1920x1200: the fixed "
                 "4x600 Mbps DPHY link cannot carry more)";

    if (why) *why = reason;
    return reason ? -1 : 0;
}

int kvm_geom_build(kvm_geom *g, int w, int h)
{
    memset(g, 0, sizeof(*g));
    if (kvm_geom_check(w, h, NULL) != 0) return -1;

    /* Assumption A2 (see the file header): pad the line stride up. This is a
     * no-op at 1920 and at every other standard width except 1366 -> 1376.
     * If a non-1080p bring-up ever produces sheared/garbage frames, the first
     * experiment is KVM_GEOM_STRIDE_ALIGN = 2 (stride == width). */
    int stride = align_up_i(w, KVM_GEOM_STRIDE_ALIGN);

    g->w = w; g->h = h; g->stride = stride;

    memcpy(g->dev_attr,    TPL_dev_attr,  KVM_GEOM_DEV_ATTR_LEN);
    memcpy(g->dev_attr2,   TPL_dev_attr2, KVM_GEOM_DEV_ATTR_LEN);
    memcpy(g->pipe_create, TPL_nr35,      KVM_GEOM_PIPE_LEN);
    memcpy(g->pipe_attr,   TPL_nr42,      KVM_GEOM_PIPE_LEN);
    memcpy(g->chn_attr,    TPL_nr48,      KVM_GEOM_CHN_LEN);

    put_u32le(g->dev_attr,  DEVATTR_W_OFF,      (uint32_t)w);
    put_u32le(g->dev_attr,  DEVATTR_H_OFF,      (uint32_t)h);
    put_u32le(g->dev_attr,  DEVATTR_STRIDE_OFF, (uint32_t)stride);

    /* dev attr #2: the vendor's second SetDevAttr zeroes the stride word and
     * the {01,02,03} lane bytes; only w/h are parameterised (assumption A4). */
    put_u32le(g->dev_attr2, DEVATTR_W_OFF, (uint32_t)w);
    put_u32le(g->dev_attr2, DEVATTR_H_OFF, (uint32_t)h);

    /* CreatePipe carries no stride in the captured bytes (assumption A3). */
    put_u32le(g->pipe_create, PIPE_W_OFF, (uint32_t)w);
    put_u32le(g->pipe_create, PIPE_H_OFF, (uint32_t)h);

    put_u32le(g->pipe_attr, PIPE_W_OFF,      (uint32_t)w);
    put_u32le(g->pipe_attr, PIPE_H_OFF,      (uint32_t)h);
    put_u32le(g->pipe_attr, PIPE_STRIDE_OFF, (uint32_t)stride);

    put_u32le(g->chn_attr, CHN_W_OFF,      (uint32_t)w);
    put_u32le(g->chn_attr, CHN_H_OFF,      (uint32_t)h);
    put_u32le(g->chn_attr, CHN_STRIDE_OFF, (uint32_t)stride);

    /* os_mem nr1 descriptor: the SOURCE geometry, not the padded stride -- the
     * Stage-3 differential capture read these two words as {width,height}. */
    g->osmem_desc[0] = (uint32_t)w;
    g->osmem_desc[1] = (uint32_t)h;

    /* Pool floorplan. BlkSize follows the STRIDE (the VIN DMAs stride*2 bytes
     * per line), so a padded stride never under-sizes a block. The pool packs
     * [BlkCnt meta pages][block 0][block 1]... with each block at a
     * PAGE-ALIGNED pitch -- device-verified 2026-08-17 by dumping the live
     * region; the meta-page offset and the pitch are what kvm_cap_get needs to
     * land on the real frame (the old base + idx*BlkSize formula was the green
     * top-bar / scrolling bug). */
    g->blk_size  = (uint32_t)stride * (uint32_t)h * KVM_GEOM_BPP;
    g->blk_pitch = (g->blk_size + 4095u) & ~4095u;
    g->pool_span = (uint64_t)KVM_POOL_METASIZE * KVM_POOL_BLKCNT_OPEN
                 + (uint64_t)KVM_POOL_BLKCNT_OPEN * g->blk_pitch;
    return 0;
}
