/*
 * geom_identity_test.c -- the 1080p REGRESSION PROOF for issue #17.
 *
 * The open capture backend can only be hardware-tested at 1920x1080 (no other
 * HDMI source is available), so 1080p bit-identity is the one property that is
 * actually checkable against the device-proven configuration. This test proves
 * it mechanically instead of by inspection:
 *
 *   every payload byte, every allocator descriptor word and every pool size
 *   that kvm_geom_build(1920,1080) produces is compared against the ORIGINAL
 *   hardcoded constants.
 *
 * The REF_* arrays below were extracted programmatically from the pre-change
 * kvm_capture_open.c (`git show 97507e3:pkgs/kvm-encoder/src/kvm_capture_open.c`
 * -- the commit #17 was implemented on top of) -- they are the vendor-captured
 * bytes as they were shipped and device-validated, not a re-transcription. The
 * pool/descriptor reference values are likewise the literal pre-change
 * expressions.
 *
 * It also pins the non-1080p behaviour that has NO hardware coverage yet, so a
 * later edit cannot silently change it: 1280x720 golden vectors, the stride
 * padding rule, and the accept/reject envelope.
 *
 * Run: nix build .#checks.x86_64-linux.open-capture-geometry -L
 */
#include <stdio.h>
#include <string.h>
#include <stdint.h>

#include "kvm_capture_geom.h"

static int failures;

static void chk_mem(const char *what, const void *got, const void *want, size_t n)
{
    if (memcmp(got, want, n) == 0) { printf("  ok    %-28s %zu bytes identical\n", what, n); return; }
    failures++;
    printf("  FAIL  %s: %zu bytes differ\n", what, n);
    const unsigned char *g = got, *w = want;
    for (size_t i = 0, shown = 0; i < n && shown < 24; i++)
        if (g[i] != w[i]) { printf("        @0x%03zx got 0x%02x want 0x%02x\n", i, g[i], w[i]); shown++; }
}

static void chk_u64(const char *what, uint64_t got, uint64_t want)
{
    if (got == want) { printf("  ok    %-28s %llu (0x%llx)\n", what,
                              (unsigned long long)got, (unsigned long long)got); return; }
    failures++;
    printf("  FAIL  %s: got %llu (0x%llx) want %llu (0x%llx)\n", what,
           (unsigned long long)got, (unsigned long long)got,
           (unsigned long long)want, (unsigned long long)want);
}

static uint32_t u32le(const unsigned char *p, unsigned off)
{
    return (uint32_t)p[off] | ((uint32_t)p[off+1] << 8)
         | ((uint32_t)p[off+2] << 16) | ((uint32_t)p[off+3] << 24);
}

