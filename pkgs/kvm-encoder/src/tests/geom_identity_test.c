/* Pre-change scalars, copied from the same source:
 *   S.blk_size  = (uint32_t)w * (uint32_t)h * 2u;
 *   S.blk_pitch = (S.blk_size + 4095u) & ~4095u;
 *   desc[0] = w; desc[1] = h;                      (os_mem nr1)
 *   *(uint64_t *)(fp + 0x28) = KVM_POOL_METASIZE;  (pool nr22 floorplan)
 *   *(uint64_t *)(fp + 0x30) = S.blk_size;
 *   *(uint32_t *)(fp + 0x38) = KVM_POOL_BLKCNT_OPEN;
 */
#define REF_W 1920
#define REF_H 1080
#define REF_BLK_SIZE  ((uint32_t)REF_W * (uint32_t)REF_H * 2u)
#define REF_BLK_PITCH ((REF_BLK_SIZE + 4095u) & ~4095u)

/* ================================ the proof ================================ */
static void test_1080p_identity(void)
{
    kvm_geom g;
    printf("[1080p bit-identity vs the pre-#17 hardcoded constants]\n");
    if (kvm_geom_build(&g, REF_W, REF_H) != 0) {
        printf("  FAIL  kvm_geom_build(1920,1080) rejected the device-proven geometry\n");
        failures++;
        return;
    }
    chk_mem("proton nr17/nr21 dev_attr",  g.dev_attr,    REF_dev_attr,  sizeof REF_dev_attr);
    chk_mem("proton nr21 dev_attr #2",    g.dev_attr2,   REF_dev_attr2, sizeof REF_dev_attr2);
    chk_mem("proton nr35 CreatePipe",     g.pipe_create, REF_nr35,      sizeof REF_nr35);
    chk_mem("proton nr42 SetPipeAttr",    g.pipe_attr,   REF_nr42,      sizeof REF_nr42);
    chk_mem("proton nr48 SetChnAttr",     g.chn_attr,    REF_nr48,      sizeof REF_nr48);
    chk_u64("os_mem nr1 desc word0",      g.osmem_desc[0], REF_W);
    chk_u64("os_mem nr1 desc word1",      g.osmem_desc[1], REF_H);
    chk_u64("pool nr22 BlkSize",          g.blk_size,      REF_BLK_SIZE);
    chk_u64("pool block pitch",           g.blk_pitch,     REF_BLK_PITCH);
    chk_u64("line stride (px)",           (uint64_t)g.stride, REF_W);
    /* The floorplan constants must not have drifted either. */
    chk_u64("pool MetaSize",              KVM_POOL_METASIZE, 4096);
    chk_u64("pool BlkCnt",                KVM_POOL_BLKCNT_OPEN, 4);
    chk_u64("pool span",                  g.pool_span,
            (uint64_t)4096 * 4 + (uint64_t)4 * REF_BLK_PITCH);
}

/* Golden vectors for a geometry the hardware has NOT been tested at. These do
 * not prove correctness on silicon -- they pin the parameterization so a later
 * refactor cannot silently drop a field back to its 1080p constant. */
static void test_720p_vectors(void)
{
    kvm_geom g;
    printf("\n[1280x720 golden vectors (no hardware coverage -- pins the math)]\n");
    if (kvm_geom_build(&g, 1280, 720) != 0) { printf("  FAIL  720p rejected\n"); failures++; return; }
    chk_u64("stride", (uint64_t)g.stride, 1280);
    chk_u64("dev_attr  width @0x58",  u32le(g.dev_attr, 0x58), 1280);
    chk_u64("dev_attr  height@0x5c",  u32le(g.dev_attr, 0x5c), 720);
    chk_u64("dev_attr  stride@0xdc",  u32le(g.dev_attr, 0xdc), 1280);
    chk_u64("dev_attr2 width @0x58",  u32le(g.dev_attr2, 0x58), 1280);
    chk_u64("dev_attr2 height@0x5c",  u32le(g.dev_attr2, 0x5c), 720);
    chk_u64("dev_attr2 stride@0xdc",  u32le(g.dev_attr2, 0xdc), 0); /* zeroed as captured */
    chk_u64("nr35 width @0x1c",       u32le(g.pipe_create, 0x1c), 1280);
    chk_u64("nr35 height@0x20",       u32le(g.pipe_create, 0x20), 720);
    chk_u64("nr35 @0x24 (no stride)", u32le(g.pipe_create, 0x24), 0);
    chk_u64("nr42 width @0x1c",       u32le(g.pipe_attr, 0x1c), 1280);
    chk_u64("nr42 height@0x20",       u32le(g.pipe_attr, 0x20), 720);
    chk_u64("nr42 stride@0x24",       u32le(g.pipe_attr, 0x24), 1280);
    chk_u64("nr48 width @0x08",       u32le(g.chn_attr, 0x08), 1280);
    chk_u64("nr48 height@0x0c",       u32le(g.chn_attr, 0x0c), 720);
    chk_u64("nr48 stride@0x10",       u32le(g.chn_attr, 0x10), 1280);
    chk_u64("desc word0",             g.osmem_desc[0], 1280);
    chk_u64("desc word1",             g.osmem_desc[1], 720);
    chk_u64("BlkSize",                g.blk_size, 1280u * 720u * 2u);
    chk_u64("block pitch",            g.blk_pitch, (1280u * 720u * 2u + 4095u) & ~4095u);

    /* Non-geometry bytes must survive verbatim at any resolution: compare the
     * whole 1080p reference with the geometry words masked out. */
    unsigned char a[KVM_GEOM_DEV_ATTR_LEN], b[KVM_GEOM_DEV_ATTR_LEN];
    memcpy(a, g.dev_attr, sizeof a); memcpy(b, REF_dev_attr, sizeof b);
    memset(a + 0x58, 0, 8); memset(b + 0x58, 0, 8);
    memset(a + 0xdc, 0, 4); memset(b + 0xdc, 0, 4);
    chk_mem("dev_attr non-geometry bytes", a, b, sizeof a);
}

/* 1366x768 is the one common HDMI mode whose width is not 16-px aligned.
 * Stride == width (align 2): hardware-proven 2026-08-31 -- the VC8000E reads
 * input lines packed at the true width (a 1376-stride fill sheared 10 px/row)
 * and the vendor MPI programs nWidthStride = w. */
static void test_stride_padding(void)
{
    kvm_geom g;
    printf("\n[1366x768 -- the only standard mode with a non-16-aligned width]\n");
    if (kvm_geom_build(&g, 1366, 768) != 0) { printf("  FAIL  1366x768 rejected\n"); failures++; return; }
    chk_u64("stride == width",        (uint64_t)g.stride, 1366);
    chk_u64("nr48 width @0x08",       u32le(g.chn_attr, 0x08), 1366);
    chk_u64("nr48 stride@0x10",       u32le(g.chn_attr, 0x10), 1366);
    chk_u64("BlkSize uses stride",    g.blk_size, 1366u * 768u * 2u);
}

static void expect(int w, int h, int want_ok)
{
    const char *why = NULL;
    int ok = kvm_geom_check(w, h, &why) == 0;
    if (ok == want_ok) {
        printf("  ok    %4dx%-4d %-8s %s\n", w, h, ok ? "accept" : "reject", ok ? "" : why);
    } else {
        failures++;
        printf("  FAIL  %4dx%-4d expected %s, got %s (%s)\n", w, h,
               want_ok ? "accept" : "reject", ok ? "accept" : "reject", why ? why : "");
    }
}

static void test_envelope(void)
{
    printf("\n[supported geometry envelope]\n");
    expect(1920, 1080, 1);
    expect(1280,  720, 1);
    expect(1920, 1200, 1);
    expect(1600,  900, 1);
    expect(1366,  768, 1);
    expect(1024,  768, 1);
    expect( 640,  480, 1);
    expect(   0,    0, 0);   /* HDMI unlocked */
    expect(  -1,  480, 0);
    expect(1921, 1080, 0);   /* odd width  */
    expect(1920, 1081, 0);   /* odd height */
    expect(  32,   32, 0);   /* below the floor */
    expect(2560, 1440, 0);   /* beyond the DPHY budget */
    expect(3840, 2160, 0);
}

/* A rejected geometry must leave nothing behind for a caller to drive. */
static void test_reject_zeroes(void)
{
    kvm_geom g;
    printf("\n[rejected geometry produces no payloads]\n");
    memset(&g, 0xa5, sizeof g);
    if (kvm_geom_build(&g, 2560, 1440) == 0) { printf("  FAIL  build accepted 2560x1440\n"); failures++; return; }
    unsigned char zero[sizeof g];
    memset(zero, 0, sizeof zero);
    chk_mem("kvm_geom zeroed on reject", &g, zero, sizeof g);
}

int main(void)
{
    printf("open-capture geometry self-test (issue #17)\n\n");
    test_1080p_identity();
    test_720p_vectors();
    test_stride_padding();
    test_envelope();
    test_reject_zeroes();
    printf("\n%s: %d failure(s)\n", failures ? "FAILED" : "PASSED", failures);
    return failures ? 1 : 0;
}
